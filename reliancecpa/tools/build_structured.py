#!/usr/bin/env python3
"""Step 3: modulize the IN pages, then annotate and clean the result.

1. writes content/overrides/*.json for the two pages the generic heuristics cannot segment (staff profiles, article index)
2. runs liftkit/tools/modulize.py for this project (IN pages only: scope.json / excluded-pages.json drop the rest)
3. annotates every structured page with `scope` (new path, role, tier, ...) and a `short_title`,
   lifts the repeated closing call to action into content/_shared-closings.json, swaps login-button images for links,
   unlinks links to the dropped dental/veterinary pages.
"""
import collections, json, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
STUDIO = ROOT.parent
sys.path.insert(0, str(HERE))
import build_scope as S
import sitemap_data as D

PAGES, INM, OUT, _ = S.build()
SCOPE = {s: e for s, e in OUT.items()}
MD = re.compile(r"\[([^\]]*)\]\(([^)]*)\)")


def plain(t):
    return re.sub(r"\s+", " ", MD.sub(r"\1", (t or "").replace("**", "").replace("*", ""))).strip()


def img_slot(b):
    return {"src": b["src"], "alt": b.get("alt", "")}


# Client corrections (Thom, 2026-11-06): Kim Nguyen is the owner now; Amol Nirgudkar no longer works at the firm,
# so his "can be reached at" author lines are dropped from the articles that carry them.
ROLE_FIX = {"Kim Nguyen": "Owner"}
FORMER_STAFF = re.compile(r"Amol Nirgudkar|amol@reliancecpa\.com", re.I)


def drop_former_staff(node, counter):
    if isinstance(node, list):
        out = []
        for x in node:
            if isinstance(x, dict) and isinstance(x.get("text"), str) and FORMER_STAFF.search(x["text"]):
                counter["former_staff_lines_dropped"] += 1
                continue
            out.append(drop_former_staff(x, counter))
        return out
    if isinstance(node, dict):
        return {k: drop_former_staff(v, counter) for k, v in node.items()}
    return node


# ---------------------------------------------------------------- overrides
def staff_override():
    d = PAGES["staff-profiles.htm"]
    bl = [b for b in d["blocks"] if b.get("region", "main") == "main"]
    title = plain(bl[0]["text"])
    people, cur = [], None
    for b in bl[1:]:
        t, tx = b["type"], b.get("text", "")
        if t == "img":
            cur = {"image": img_slot(b), "name": None, "role": None, "links": [], "body": []}
            people.append(cur)
        elif t == "p" and re.match(r"^_{5,}", tx):
            cur = None if cur is None else cur
        elif t == "p" and re.match(r"^\*\*[^*]+\*\*\s*\n+[A-Z][^\n]*\n+\[", tx) and not tx.startswith("**Professional") and not tx.startswith("**Education") and not tx.startswith("**Personal"):
            m = re.match(r"^\*\*([^*]+)\*\*\s*\n+([^\n]+)\n+\[([^\]]+)\]\((mailto:[^)]+)\)", tx)
            cur = {"image": None, "name": m.group(1), "role": m.group(2), "links": [{"text": m.group(3), "href": m.group(4)}], "body": []}
            people.append(cur)
        elif t == "p" and cur is not None:
            if cur["name"] is None:
                cur["name"] = plain(tx)
            elif cur["role"] is None:
                parts = [x for x in re.split(r"\n+", tx) if x.strip()]
                cur["role"] = plain(parts[0])
                for x in parts[1:]:
                    m = MD.search(x)
                    if m:
                        cur["links"].append({"text": m.group(1), "href": m.group(2).replace("linkto:", "mailto:")})
            else:
                cur["body"].append({"type": "p", "text": re.sub(r"^(\*\*[^*]+\*\*)\s*\n+", r"\1 ", tx)})
    mods = [{"module": "title-banner", "slots": {"title": title}}]
    for p in people:
        if p["name"] in ROLE_FIX:
            if p.get("image") and p["image"].get("alt"):
                p["image"]["alt"] = p["image"]["alt"].replace(p["role"], ROLE_FIX[p["name"]])
            p["role"] = ROLE_FIX[p["name"]]
        slots = {"image": p["image"], "name": p["name"], "role": p["role"], "links": p["links"], "body": p["body"]}
        mods.append({"module": "profile", "slots": {k: v for k, v in slots.items() if v}})
    return {"mode": "replace", "template": "about-team", "modules": mods,
            "_about": "Generated by tools/build_structured.py. The live staff page has names in <p>, not headings, so the generic profile rule misses; `profile` here also carries `body` (bio paragraphs) and email links. Valerie Stickeler has no photo on the live page."}


def articles_override():
    groups = collections.OrderedDict([("tax", "Taxes"), ("accounting", "Records, payroll and books"), ("consulting", "Business, estate and financial planning"), ("general", "Choosing a CPA")])
    items = collections.defaultdict(list)
    for slug, v in INM.items():
        if v["role"] == "resource-article":
            title = plain(next(b["text"] for b in PAGES[slug]["blocks"] if b["type"] in ("h3", "h2", "h1")))
            items[v["tag"]].append({"text": title, "href": "https://www.reliancecpa.com" + S.path_of(PAGES[slug]["url"]), "page": slug, "new_path": v["new_path"]})
    mods = [{"module": "title-banner", "slots": {"title": "Articles"}}]
    for k, lab in groups.items():
        links = sorted(items[k], key=lambda x: x["text"].lower())
        if links:
            mods.append({"module": "link-list", "slots": {"title": lab, "level": 2, "links": links}})
    old = sum(len(re.findall(r"\]\(", c)) for b in PAGES["articles.html"]["blocks"] if b["type"] == "table" for r in b["rows"] for c in r)
    return {"mode": "replace", "template": "resource-media", "modules": mods,
            "_about": f"Generated by tools/build_structured.py. The live Articles page is two tables of {old} links into the dropped article library; the new index lists only the articles carried to the new site, grouped by tier tag."}


# ---------------------------------------------------------------- annotation / cleaning
CTA_START = re.compile(r"^(To (learn|speak|inquire|find)|For (more|further)|Please|If you (would|are|need)|Regardless|Let the|Contact|We invite|Call us)", re.I)
CTA_FREE = re.compile(r"free[^.]{0,60}(check.?up|consultation)|(check.?up|consultation)[^.]{0,60}free", re.I)
DROPPED_UNLINK = re.compile(r"reliancecpa\.com/(dental|veterinar|basic-valuation|vet-)", re.I)


def short_title(slug, d):
    v = INM[slug]
    if v.get("nav_label"):
        return v["nav_label"]
    return None


def walk_unlink(node, counter):
    if isinstance(node, str):
        def r(m):
            if DROPPED_UNLINK.search(m.group(2)):
                counter["unlinked"] += 1
                return m.group(1)
            return m.group(0)
        return MD.sub(r, node)
    if isinstance(node, list):
        return [walk_unlink(x, counter) for x in node]
    if isinstance(node, dict):
        return {k: (v if k in ("src",) else walk_unlink(v, counter)) for k, v in node.items()}
    return node


def clean_pages():
    sdir = ROOT / "content/structured"
    shared = {"free-checkup": {"purpose": "the closing 'contact us for a free (no-obligation) financial check-up' paragraph that ends most service and article pages",
                               "canonical": "Contact Reliance Consulting today for a free, no obligation “check up” of your business or individual financial health.",
                               "canonical_source": "closing paragraph of business-tax.htm, income-tax-services.htm, payroll-services.htm, quickbooks-accountant.htm and tax-preparation.htm (same sentence, different lead-in)",
                               "pages": []}}
    stats = collections.Counter()
    for f in sorted(sdir.glob("*.json")):
        if f.name.startswith("_"):
            continue
        d = json.loads(f.read_text())
        slug = d["slug"]
        v = INM[slug]
        # closing CTA
        for mi in range(len(d["modules"]) - 1, -1, -1):
            m = d["modules"][mi]
            body = m["slots"].get("body") or m["slots"].get("paragraphs")
            if body is None:
                if m["module"] in ("title-banner", "image"):
                    break
                continue
            last = body[-1]
            txt = last["text"] if isinstance(last, dict) else last
            if CTA_START.search(plain(txt)) and CTA_FREE.search(plain(txt)) and len(plain(txt).split()) <= 60 and slug not in ("home",):
                shared["free-checkup"]["pages"].append({"slug": slug, "original": txt})
                body.pop()
                if not body:
                    d["modules"].pop(mi)
                d["closing"] = "free-checkup"
                stats["closing_cta"] += 1
            break
        # login-button image mislabelled as a logo row
        for m in d["modules"]:
            if m["module"] == "logo-row" and any("login" in (x.get("alt", "") + x["src"]).lower() for x in m["slots"]["logos"]):
                m["module"] = "link-list"
                m["slots"] = {"links": [{"text": x.get("alt") or "Client Login", "href": x.get("href", "")} for x in m["slots"]["logos"]]}
                stats["login_image_to_link"] += 1
        c = collections.Counter()
        d["modules"] = walk_unlink(d["modules"], c)
        d["modules"] = drop_former_staff(d["modules"], stats)
        stats["links_unlinked_dental_vet"] += c["unlinked"]
        d["scope"] = {k: v[k] for k in ("new_path", "role", "tier", "tag", "merge_into") if v.get(k)}
        d["scope"]["old_path"] = S.path_of(PAGES[slug]["url"])
        st = short_title(slug, d)
        if st:
            d["short_title"] = st
        # reorder keys: url slug template ... scope
        f.write_text(json.dumps(d, indent=1, ensure_ascii=False))
    (ROOT / "content/_shared-closings.json").write_text(json.dumps({
        "_about": "Stock closing call to action carried by many pages, recorded once. Each page's own wording is kept here under `pages` (nothing lost); the structured page carries closing: 'free-checkup' instead. The extractor already skipped the social-sharing widgets (class 'socialize') in the main region and the Google+ links live only in the global header top bar (_global.json); neither reaches the structured pages.",
        "blocks": shared}, indent=1, ensure_ascii=False))
    return stats, len(shared["free-checkup"]["pages"])


def main():
    odir = ROOT / "content/overrides"
    odir.mkdir(exist_ok=True)
    (odir / "staff-profiles.htm.json").write_text(json.dumps(staff_override(), indent=1, ensure_ascii=False))
    (odir / "articles.html.json").write_text(json.dumps(articles_override(), indent=1, ensure_ascii=False))
    py = STUDIO / "liftkit/.venv/bin/python"
    r = subprocess.run([str(py), str(STUDIO / "liftkit/tools/modulize.py"), "--project", str(ROOT)], capture_output=True, text=True)
    print(r.stdout[-1800:], r.stderr[-800:])
    print(clean_pages())


if __name__ == "__main__":
    main()
